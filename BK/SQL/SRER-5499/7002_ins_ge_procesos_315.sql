-- GE_PROCESOS_DET paso 1: archivo CF-1046-YYYYMMDD.csv
MERGE INTO IT.GE_PROCESOS_DET tgt
USING (SELECT 315 cod_proceso, 1 nro_orden FROM DUAL) src
ON (tgt.COD_PROCESO = src.cod_proceso AND tgt.NRO_ORDEN = src.nro_orden)
WHEN NOT MATCHED THEN
  INSERT (COD_PROCESO, NRO_ORDEN, DESCRIPCION, COD_PROGRAMA, OBLIGATORIO, FRECUENCIA, ACTIVO,
          NOM_ARCHIVO, FORMATO, CON_CABECERA, VAR_SUSTITUCION)
  VALUES (315, 1, 'Generacion Archivo CF-1046', 'CD_CF_ARC', 'S', 'D', 'S',
          '&NA', 'CSV', 'N',
          '&NA=select ''CF-''||pag_gen.fu_obt_cod_entidad||''-''||to_char(to_date(&FEC_CF),''yyyymmdd'') from dual;')
WHEN MATCHED THEN
  UPDATE SET tgt.DESCRIPCION     = 'Generacion Archivo CF-1046',
             tgt.COD_PROGRAMA    = 'CD_CF_ARC',
             tgt.OBLIGATORIO     = 'S',
             tgt.FRECUENCIA      = 'D',
             tgt.ACTIVO          = 'S',
             tgt.NOM_ARCHIVO     = '&NA',
             tgt.FORMATO         = 'CSV',
             tgt.CON_CABECERA    = 'N',
             tgt.VAR_SUSTITUCION = '&NA=select ''CF-''||pag_gen.fu_obt_cod_entidad||''-''||to_char(to_date(&FEC_CF),''yyyymmdd'') from dual;';

