BEGIN
  PRE_INI_APLICACION;
  PAE_CNF.G_COD_MODULO := 1;

  MERGE INTO IT.BA_CONSULTAS tgt
  USING (SELECT 'CD_CF_ARC' cod FROM DUAL) src
  ON (tgt.COD_CONSULTA = src.cod)
  WHEN NOT MATCHED THEN
    INSERT (COD_CONSULTA, DESCRIPCION, COD_USUARIO, TIPO, PERMISO, DET_SQL, FILTROS,
            COL_CORTES, COL_SUMAS, OBSERVACION)
    VALUES ('CD_CF_ARC',
            'GENERACION ARCHIVO CF-1046 ALTA PERSONAS BCP',
            USER, 'P',
            'ADM. DE SISTEMAS-ADMINISTRADOR DE SISTEMAS o USUARIOHML-USUARIO HOMOLOGACION',
            'SELECT p.LINEA_CSV 
FROM SV_CF_ALT_PERSONAS p
where &P_FILTROS
ORDER BY p.NRO_LINEA',
            '',
            '', '', '')
  WHEN MATCHED THEN
    UPDATE SET tgt.DESCRIPCION = 'GENERACION ARCHIVO CF-1046 ALTA PERSONAS BCP',
               tgt.TIPO        = 'P',
               tgt.DET_SQL     = 'SELECT p.LINEA_CSV 
FROM SV_CF_ALT_PERSONAS p
where &P_FILTROS
ORDER BY p.NRO_LINEA';

  MERGE INTO IT.BA_CONSULTAS tgt
  USING (SELECT 'CD_CF_EXCL' cod FROM DUAL) src
  ON (tgt.COD_CONSULTA = src.cod)
  WHEN NOT MATCHED THEN
    INSERT (COD_CONSULTA, DESCRIPCION, COD_USUARIO, TIPO, PERMISO, DET_SQL, FILTROS,
            COL_CORTES, COL_SUMAS, OBSERVACION)
    VALUES ('CD_CF_EXCL',
            'DETALLE EXCLUSIONES CF ALTA PERSONAS BCP',
            USER, 'P',
            'ADM. DE SISTEMAS-ADMINISTRADOR DE SISTEMAS o USUARIOHML-USUARIO HOMOLOGACION',
            'SELECT d.COD_REGLA, d.ACCION, d.TIPO_IDENT, d.NRO_DOCUMENTO, d.TIPO_PER, d.APELLIDO, d.NOMBRE, d.FECHA_NAC, d.FECHA_VENC_DOC, d.GENERO, d.PAIS_NACIMIENTO, d.COD_PERSONA, d.MOTIVO, d.VALOR_ORIGINAL, d.VALOR_CORREGIDO 
FROM SV_CF_EXCL_DETALLE d
WHERE &P_FILTROS
ORDER BY COD_REGLA, TIPO_IDENT, NRO_DOCUMENTO',
            '',
            '', '', '')
  WHEN MATCHED THEN
    UPDATE SET tgt.DESCRIPCION = 'DETALLE EXCLUSIONES CF ALTA PERSONAS BCP',
               tgt.TIPO        = 'P',
               tgt.DET_SQL     = 'SELECT d.COD_REGLA, d.ACCION, d.TIPO_IDENT, d.NRO_DOCUMENTO, d.TIPO_PER, d.APELLIDO, d.NOMBRE, d.FECHA_NAC, d.FECHA_VENC_DOC, d.GENERO, d.PAIS_NACIMIENTO, d.COD_PERSONA, d.MOTIVO, d.VALOR_ORIGINAL, d.VALOR_CORREGIDO 
FROM SV_CF_EXCL_DETALLE d
WHERE &P_FILTROS
ORDER BY COD_REGLA, TIPO_IDENT, NRO_DOCUMENTO';

  COMMIT;
END;
